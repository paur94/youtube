import { BotIcon, HandIcon } from "lucide-react";

import { Badge } from "@/components/ui/badge";
import {
  ASSET_STATUS_LABELS,
  CHARACTER_STATUS_LABELS,
  JOB_STATUS_LABELS,
  PLAN_STATUS_LABELS,
  SCENE_STATUS_LABELS,
  type AssetStatus,
  type CharacterStatus,
  type JobMode,
  type JobStatus,
  type PlanStatus,
  type SceneStatus,
} from "@/lib/production";
import { cn } from "@/lib/utils";

const MUTED = "bg-muted text-muted-foreground";
const AMBER = "bg-amber-100 text-amber-800 dark:bg-amber-950 dark:text-amber-300";
const SKY = "bg-sky-100 text-sky-800 dark:bg-sky-950 dark:text-sky-300";
const VIOLET = "bg-violet-100 text-violet-800 dark:bg-violet-950 dark:text-violet-300";
const GREEN = "bg-emerald-100 text-emerald-800 dark:bg-emerald-950 dark:text-emerald-300";
const RED = "bg-rose-100 text-rose-800 dark:bg-rose-950 dark:text-rose-300";

const PLAN_STYLES: Record<PlanStatus, string> = { planning: MUTED, in_production: SKY, ready_for_assembly: GREEN };

export function PlanStatusBadge({ status }: { status: PlanStatus }) {
  return <Badge className={cn(PLAN_STYLES[status])}>{PLAN_STATUS_LABELS[status]}</Badge>;
}

const SCENE_STYLES: Record<SceneStatus, string> = {
  draft: MUTED,
  ready: SKY,
  generating: VIOLET,
  review: AMBER,
  failed: RED,
  approved: GREEN,
};

export function SceneStatusBadge({ status }: { status: SceneStatus }) {
  return <Badge className={cn(SCENE_STYLES[status])}>{SCENE_STATUS_LABELS[status]}</Badge>;
}

const JOB_STYLES: Record<JobStatus, string> = {
  awaiting_manual: AMBER,
  queued: SKY,
  in_progress: VIOLET,
  completed: GREEN,
  failed: RED,
  nsfw: RED,
  canceled: MUTED,
  timed_out: RED,
};

export function JobStatusBadge({ status }: { status: JobStatus }) {
  return <Badge className={cn(JOB_STYLES[status])}>{JOB_STATUS_LABELS[status]}</Badge>;
}

const ASSET_STYLES: Record<AssetStatus, string> = { pending_review: AMBER, approved: GREEN, rejected: RED };

export function AssetStatusBadge({ status }: { status: AssetStatus }) {
  return <Badge className={cn(ASSET_STYLES[status])}>{ASSET_STATUS_LABELS[status]}</Badge>;
}

const CHARACTER_STYLES: Record<CharacterStatus, string> = {
  draft: MUTED,
  approved: GREEN,
  archived: "bg-transparent text-muted-foreground border-border line-through",
};

export function CharacterStatusBadge({ status }: { status: CharacterStatus }) {
  return <Badge className={cn(CHARACTER_STYLES[status])}>{CHARACTER_STATUS_LABELS[status]}</Badge>;
}

/** Makes it obvious whether something ran through the API or was done by hand. */
export function ModeBadge({ mode }: { mode: JobMode }) {
  return mode === "api" ? (
    <Badge variant="outline" className="border-primary/40 text-primary" title="Submitted automatically through the Higgsfield API">
      <BotIcon />
      API
    </Badge>
  ) : (
    <Badge variant="outline" className="border-amber-500/40 text-amber-300" title="Generated by you in the Higgsfield web app">
      <HandIcon />
      Manual
    </Badge>
  );
}
